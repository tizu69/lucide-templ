package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"regexp"
	"strings"
)

var (
	src      = flag.String("src", "./ref/icons", "source directory")
	dst      = flag.String("dst", "../lucide.go", "destination")
	pkg      = flag.String("pkg", "lucide", "package name")
	skiptype = flag.Bool("skiptype", false, "skip type definition")
	prefix   = flag.String("prefix", "", "prefix for icon names")
)

func main() {
	flag.Parse()
	if err := generate(*src, *dst); err != nil {
		panic(err)
	}
}

func generate(src, dst string) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by lucide-templ/generate; DO NOT EDIT.\n\n")

	b.WriteString("// Package lucide contains SVG icons from the Lucide icon set.\n")
	b.WriteString("// See https://lucide.dev/ for more information.\n")
	b.WriteString("package ")
	b.WriteString(*pkg)
	b.WriteString("\n\n")

	if !*skiptype {
		b.WriteString("import (\n")
		b.WriteString("\t\"context\"\n")
		b.WriteString("\t\"html\"\n")
		b.WriteString("\t\"io\"\n")
		b.WriteString(")\n\n")

		b.WriteString("type Icon string\n\n")
		b.WriteString("func (icon Icon) Render(ctx context.Context, w io.Writer) error {\n")
		b.WriteString("\t_, err := w.Write([]byte(icon))\n")
		b.WriteString("\treturn err\n")
		b.WriteString("}\n\n")
		b.WriteString("// C returns a copy of the icon with the given class attribute.\n")
		b.WriteString("func (icon Icon) C(class string) Icon {\n")
		b.WriteString("\treturn Icon(\"<svg class=\\\"\" + html.EscapeString(class) + \"\\\" \" + string(icon[5:]))\n")
		b.WriteString("}\n\n")
	}

	// read all files in src dir
	files, err := os.ReadDir(src)
	if err != nil {
		return err
	}

	b.WriteString("const (\n")
	for _, file := range files {
		if len(file.Name()) < 4 || file.Name()[len(file.Name())-4:] != ".svg" {
			continue
		}

		f, err := os.ReadFile(src + "/" + file.Name())
		if err != nil {
			return err
		}

		filename := file.Name()[:len(file.Name())-4]
		name := ""
		for i, r := range filename {
			switch {
			case r == '-':
			case (i == 0 || filename[i-1] == '-') && (r >= 'a' && r <= 'z'):
				name += string(r - 32)
			default:
				name += string(r)
			}
		}

		b.WriteString("\t// https://lucide.dev/icons/")
		if *prefix != "" {
			b.WriteString(strings.ToLower(*prefix))
			b.WriteString("/")
		}
		b.WriteString(filename)
		if *prefix != "" {
			b.WriteString(" (")
			b.WriteString(*prefix)
			b.WriteString(")")
		}
		b.WriteString("\n")
		fmt.Fprintf(&b, "\t%s = Icon(%q)\n", name, minifySVG(string(f)))
	}
	b.WriteString(")\n")

	return os.WriteFile(dst, b.Bytes(), 0o644)
}

var (
	interTagWhitespace = regexp.MustCompile(`>[\r\n ]+<`)
	svgWhitespace      = regexp.MustCompile(`(<.*?>)|\s+`)
)

func minifySVG(svg string) string {
	svg = interTagWhitespace.ReplaceAllString(svg, "><")
	return strings.TrimSpace(
		svgWhitespace.ReplaceAllStringFunc(svg, func(match string) string {
			if strings.HasPrefix(match, "<") {
				return match
			}
			return " "
		}),
	)
}
